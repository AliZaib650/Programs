#include <iostream>
#include <cmath>
const float PI=3.14159;
const float E= 2.71828;
using namespace std;

int main()
{
    cout << sqrt(4.0) << endl;
    cout << sin(2 * PI)  << endl;
    cout << cos(2 * PI)  << endl;
    cout << pow(2.0, 2)  << endl;
    cout << log(E)  << endl;
    cout << exp(0.1)  << endl;
    cout << max(2, min(3, 4))  << endl;
    cout << sqrt(125.0)  << endl;
    cout << floor(-2.5)  << endl;
    cout << asin(0.5)  << endl;
    cout << acos(0.5)  << endl;
    cout << atan(1.0)  << endl;
    cout << ceil(-2.5)  << endl;
    cout << floor(2.5) << endl;
    cout << log10(10.0) << endl;
    cout << pow(2.0, 3) << endl;

    return 0;
}
